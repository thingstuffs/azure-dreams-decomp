#!/usr/bin/env bash
# Create build_ovl/: a view root for the unmodified upstream overlay window gate.  Matched C is
# read from src/<overlay>/ through overlays/<overlay>/first_pass_matched symlinks, the window
# YAMLs and symbol files from config/overlays/, the gate tools from tools/gate/, and the
# extracted containers, toolchain, venv and disc from the upstream checkout named in .upstream.
# Gate build outputs land in build_ovl/work/ (never in the upstream tree).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
UP="${AZURE_CLEAN_UPSTREAM:-$(cat "$ROOT/.upstream")}"
# RAW=1 builds a second root over raw/ (the untouched pinned sources) for A/B checks
if [ "${RAW:-0}" = "1" ]; then B="$ROOT/build_ovl_raw"; SRCROOT="$ROOT/raw"; else B="$ROOT/build_ovl"; SRCROOT="$ROOT/src"; fi
mkdir -p "$B/overlays" "$B/config" "$B/work/s3_splat" "$B/work/overlay_recon"
# platform-library twins (asm/psyq) and SLUS nonmatchings are generated by the SLUS split:
# run tools/build/mk_slus_root.sh + `splat split` in build_slus first
rm -rf "$B/asm"; ln -sfn "$ROOT/build_slus/asm" "$B/asm"
for o in main town dungeon dungeon_engine ovmovie; do
  mkdir -p "$B/overlays/$o"
  src="$SRCROOT/$o"
  # the engine mirror names its rows in true space; until the mirror roster is folded into the
  # dungeon rows it gates the pinned engine copies (upstream/) as-is
  [ "$o" = dungeon_engine ] && src="$ROOT/upstream/overlays/dungeon_engine/first_pass_matched"
  ln -sfn "$src" "$B/overlays/$o/first_pass_matched"
  ln -sfn "$ROOT/upstream/overlays/$o/overlay_first_pass_results.json" "$B/overlays/$o/overlay_first_pass_results.json"
done
ln -sfn "$ROOT/config/overlays"   "$B/config/overlays"
ln -sfn "$ROOT/include"           "$B/include"
rm -rf "$B/tools"; mkdir -p "$B/tools"; cp -rL "$ROOT/tools/gate/." "$B/tools/"   # real files: the gate resolves __file__
ln -sfn "$UP/toolchain"           "$B/toolchain"
ln -sfn "$UP/.venv"               "$B/.venv"
ln -sfn "$UP/bin"                 "$B/bin"
ln -sfn "$UP/work/s3_splat/extract" "$B/work/s3_splat/extract"
mkdir -p "$B/work/roundtrip"; ln -sfn "$UP/work/roundtrip/extract" "$B/work/roundtrip/extract"   # main_7fdd reads the round-trip extract
ln -sfn "$ROOT/tools/gate/extract_bins.py" "$B/work/overlay_recon/extract_bins.py"
for f in names.tsv slus_006.14.yaml slus_006.14.symbols.txt noreturn_syms.txt noreturn_syms.dungeon.txt noreturn_syms.town.txt noreturn_syms.ovmovie.txt sibcall_syms.txt sibcall_syms.dungeon.txt sibcall_syms.town.txt sibcall_syms.ovmovie.txt noreturn_false_members.jsonl; do
  [ -f "$ROOT/config/$f" ] && ln -sfn "$ROOT/config/$f" "$B/config/$f"
done
ln -sfn "$ROOT/build_slus/config/generated" "$B/config/generated"
ln -sfn "$ROOT/build_slus/build" "$B/build"
echo "gate root: $B"
