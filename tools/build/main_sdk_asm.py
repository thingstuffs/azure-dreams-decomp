#!/usr/bin/env python3
"""Regenerate the MAIN-only Sony LIBCARD/PATCH.OBJ private delay twin.

The complete linked 416-byte object must match its provenance receipt before
extracting the relocation-free 24-byte private routine. No C compiler recipe,
SDK binary download, incbin, or retail fallback participates in assembly.
The synthetic row symbol is an extent identity, not an invented Sony export.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

OBJECT_START = 0x271848
OBJECT_SIZE = 416
ROW_OFFSET = 0x17C
ROW_SIZE = 24
OBJECT_SHA256 = 'da6667239d5da39af0582721d7ca40011ec5d51becdb020d3b1c155a8e856634'
ROW_SHA256 = '3ab55a0f1f41698287658ae2491979e94fd9a912f084c47d498560a0ec7e445f'
OUTPUT = 'build_slus/asm/psyq/libcard/main_patch_delay.s'
SYMBOL = 'func_800219C4'
WORDS = (0x3C0E0032, 0x25CEFFFF, 0x15C0FFFF, 0x25CEFFFF, 0x03E00008, 0)


def verified_row(container):
    with Path(container).open('rb') as source:
        source.seek(OBJECT_START)
        obj = source.read(OBJECT_SIZE)
    if len(obj) != OBJECT_SIZE or hashlib.sha256(obj).hexdigest() != OBJECT_SHA256:
        raise ValueError('MAIN LIBCARD/PATCH.OBJ complete linked text differs from provenance receipt')
    row = obj[ROW_OFFSET:ROW_OFFSET + ROW_SIZE]
    if hashlib.sha256(row).hexdigest() != ROW_SHA256 or struct.unpack('<6I', row) != WORDS:
        raise ValueError('MAIN private PATCH delay extent differs from provenance receipt')
    return row


def assembly(row):
    words = struct.unpack('<6I', row)
    if words != WORDS:
        raise ValueError('unsupported private PATCH delay instruction stream')
    # Keep retail emission order. The branch at +8 targets itself, with the
    # second decrement in its delay slot. The return delay slot is zero.
    instructions = [
        f'lui $t6, 0x{words[0] & 0xffff:X}',
        'addiu $t6, $t6, -1',
        '.Lmain_patch_delay_loop:\n    bnez $t6, .Lmain_patch_delay_loop',
        'addiu $t6, $t6, -1',
        'jr $ra',
        'nop',
    ]
    return ('# Generated by tools/build/main_sdk_asm.py from the user disc.\n'
            '# Sony LIBCARD/PATCH.OBJ +0x17c; private, not _patch_card2.\n'
            '# Provenance: docs/evidence/main_libcard_patch_delay.md\n'
            '.include "macro.inc"\n\n.set noat\n.set noreorder\n'
            '.section .text, "ax"\n.balign 4\n\n'
            f'glabel {SYMBOL}\n    ' + '\n    '.join(instructions) +
            f'\nendlabel {SYMBOL}\n')


def generate(root):
    root = Path(root).resolve()
    row = verified_row(root/'work/disc/containers/MAIN_MAIN.BIN')
    text = assembly(row)
    output = root/OUTPUT
    # Do not write through an old build view or a shared asm directory.
    if output.is_symlink() or not output.parent.resolve().is_relative_to(root):
        raise ValueError('MAIN SDK assembly output escapes the requested root')
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    return {'source': OUTPUT, 'container': 'work/disc/containers/MAIN_MAIN.BIN',
            'object_start': hex(OBJECT_START), 'object_size': OBJECT_SIZE,
            'object_sha256': OBJECT_SHA256, 'row_start': hex(OBJECT_START + ROW_OFFSET),
            'row_size': ROW_SIZE, 'row_sha256': ROW_SHA256, 'symbol': SYMBOL,
            'source_kind': 'platform_asm', 'reviewer': 'pending'}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    args = ap.parse_args()
    try:
        print(json.dumps(generate(args.root), sort_keys=True))
    except (OSError, ValueError) as exc:
        ap.exit(1, f'Refusing MAIN SDK assembly generation: {exc}\n')


if __name__ == '__main__':
    main()
