#!/usr/bin/env python3
"""Regenerate the public byte maps using committed inputs and a user-owned disc.

Usage: python3 tools/census/regenerate.py --disc /path/to/Azure_Dreams.bin --output /tmp/census --check
No lane directory, pre-extracted container, compiler or analysis cache is needed.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools'))
import byte_map as B
import byte_map_rollout as R
from gate.disc_slice import Disc

DISC_FILES = {'main':'MAIN/MAIN.BIN', 'town':'TOWN/TOWN.BIN',
              'dungeon':'DUNGEON/DUNGEON.BIN', 'ovmovie':'OVMOVIE.BIN', 'slus':'SLUS_006.14'}


def sha(blob):
    return hashlib.sha256(blob).hexdigest()


def check_snapshot(root):
    snapshot = json.loads((root/'config/census/snapshot.json').read_text())
    for path, expected in snapshot['inputs'].items():
        if B.sha256(root/path) != expected:
            raise ValueError('B13 census snapshot input changed: '+path)
    return snapshot


def compare(generated, committed):
    """Compare the exact generated file set as well as all generated bytes."""
    def paths(directory):
        return {p.relative_to(directory).as_posix():p for p in directory.rglob('*')
                if p.is_file() and p.suffix in ('.json', '.tsv')}
    actual, expected = paths(generated), paths(committed)
    differences = []
    for name in sorted(actual.keys() | expected.keys()):
        if name not in actual or name not in expected or actual[name].read_bytes() != expected[name].read_bytes():
            differences.append(name)
    if differences:
        raise ValueError('regenerated link/ differs: '+', '.join(differences[:20]))
    return {name:sha(path.read_bytes()) for name,path in sorted(actual.items())}


def regenerate(root, disc_path, output, procs=5, check=False):
    root, output, disc_path = Path(root).resolve(), Path(output).resolve(), Path(disc_path).resolve()
    if output == root or root in output.parents and output.relative_to(root).parts[0] != 'work':
        raise ValueError('output must be outside the repository or inside ignored work/')
    output.mkdir(parents=True, exist_ok=True)
    (output/'.ignore').write_text('*\n')
    census = output/'census'
    (census/'spans').mkdir(parents=True, exist_ok=True)
    snapshot = check_snapshot(root)
    with tempfile.TemporaryDirectory(prefix='retail-', dir=output) as temp:
        bin_root = Path(temp)
        retail = {}
        with Disc(disc_path) as disc:
            for c, path in B.RETAIL.items():
                _, length = disc.locate(DISC_FILES[c])
                blob = disc.slice(DISC_FILES[c], 0, length)
                expected = snapshot['retail'][path]
                if sha(blob) != expected:
                    raise ValueError('disc container identity differs: '+c)
                retail[c] = expected
                target = bin_root/path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(blob)
        args = [sys.executable, '-B', '-I', str(root/'tools/census/census.py'),
                '--root', str(root), '--bin-root', str(bin_root),
                '--json', str(census/'census.json'), '--md', str(census/'census.md'),
                '--spans-dir', str(census/'spans'), '--procs', str(procs),
                '--bank-map', str(root/'config/census/cd_bank_map.json'),
                '--typed-data', str(root/'config/census/typed_data.jsonl'),
                '--replayed-code', str(root/'config/census/replayed_prefixes.jsonl')]
        print('Recomputing census detectors, precision, masked prefixes and neighbours.', flush=True)
        subprocess.run(args, cwd=root, check=True)
        inputs = dict(snapshot['inputs'])
        for directory, pattern in (('config/census','*'), ('tools/census','*.py')):
            for path in sorted((root/directory).glob(pattern)):
                if path.is_file():
                    inputs[path.relative_to(root).as_posix()] = B.sha256(path)
        outputs = {p.relative_to(census).as_posix():B.sha256(p)
                   for p in sorted(census.rglob('*')) if p.is_file() and p.name != 'receipt.json'}
        R.write_json(census/'receipt.json', dict(base=snapshot['base'], inputs=inputs,
                     outputs=outputs, retail=retail, schema='azure-clean.census-replay.v1'))
        receipt = R.build(root, output, census, bin_root, disc_path, output/'link')
    hashes = compare(output/'link', root/'link') if check else {
        p.relative_to(output/'link').as_posix():B.sha256(p)
        for p in sorted((output/'link').rglob('*')) if p.is_file()}
    proof = dict(result='PASS', command='python3 tools/census/regenerate.py --disc DISC --output TEMP --check',
                 generated_files=len(hashes), generated_bytes=sum(p.stat().st_size for p in (output/'link').rglob('*') if p.is_file()),
                 map_set_sha256=sha(json.dumps(hashes,sort_keys=True,separators=(',',':')).encode()),
                 committed_comparison='diff empty' if check else 'not requested',
                 ignored_input_dependencies=[], cached_detector_inputs=[],
                 census_totals=receipt['census_totals'])
    R.write_json(output/'regeneration_receipt.json', proof)
    print(json.dumps(proof, indent=2), flush=True)
    return proof


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, default=ROOT)
    p.add_argument('--disc', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--procs', type=int, default=5)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    try:
        regenerate(a.root, a.disc, a.output, a.procs, a.check)
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as exc:
        p.exit(1, 'census regeneration: '+str(exc)+'\n')


if __name__ == '__main__':
    main()
